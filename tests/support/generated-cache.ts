/**
 * A disk cache for what tests generate slowly and deterministically from an addon version and the code that generates
 * it (the option reference: about two minutes per game). An entry is keyed by its inputs: a name, the addon version
 * and a hash of the generating code, i.e. every source file the generator's entry module reaches through its imports
 * (relative and `@/` imports, followed transitively) plus the versions of the packages it imports. Any change to that
 * code is a new key, so the value is generated fresh and checked by the tests again; the cache can never hand a test
 * a value the current code wouldn't make. Entries live in `.cache/generated/` (gitignored); deleting it is always safe.
 *
 * Test files running in parallel (the shards of one suite) generate each entry once: the first takes a lock and the
 * others wait for its file.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, statSync } from "node:fs";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(__dirname, "../..");
export const GENERATED_CACHE_DIR = path.join(ROOT, ".cache/generated");

const EXTENSIONS = ["", ".ts", ".tsx", ".json", "/index.ts"];
const IMPORT = /(?:^|[\s;])(?:import|export)\s[^"';]*?from\s*["']([^"']+)["']|(?:^|[\s;])import\s*\(?\s*["']([^"']+)["']/g;

function resolveImport(from: string, spec: string): string | undefined {
  const base = spec.startsWith("@/") ? path.join(ROOT, "src", spec.slice(2)) : spec.startsWith(".") ? path.resolve(path.dirname(from), spec) : undefined;
  if (!base) return undefined;
  for (const ext of EXTENSIONS) {
    const file = base + ext;
    if (existsSync(file) && statSync(file).isFile()) return file;
  }
  return undefined;
}

function packageVersion(spec: string): string | undefined {
  if (spec.startsWith(".") || spec.startsWith("@/")) return undefined;
  const name = spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0];
  const file = path.join(ROOT, "node_modules", name, "package.json");
  return existsSync(file) ? `${name}@${(JSON.parse(readFileSync(file, "utf8")) as { version: string }).version}` : undefined;
}

/**
 * A hash of the code `entry` (a path from the repo root) runs: the contents of every file it reaches through relative
 * and `@/` imports, and the version of every package it imports.
 */
export function sourceHash(entry: string): string {
  const files = new Set<string>();
  const packages = new Set<string>();
  const visit = (file: string) => {
    if (files.has(file)) return;
    files.add(file);
    if (!/\.tsx?$/.test(file)) return;
    for (const m of readFileSync(file, "utf8").matchAll(IMPORT)) {
      const spec = m[1] ?? m[2];
      const resolved = resolveImport(file, spec);
      if (resolved) visit(resolved);
      // A package: its version. Anything else unresolved (an import-like line in a comment): its text, harmlessly.
      else packages.add(packageVersion(spec) ?? spec);
    }
  };
  visit(path.resolve(ROOT, entry));
  const hash = createHash("sha256");
  for (const file of [...files].sort()) hash.update(`${path.relative(ROOT, file)}\0`).update(readFileSync(file)).update("\0");
  for (const p of [...packages].sort()) hash.update(`${p}\0`);
  return hash.digest("hex").slice(0, 16);
}

export interface Generated<T> {
  value: T;
  /** Generated by this call (not read from the cache). */
  fresh: boolean;
  file: string;
}

const LOCK_STALE_MS = 15 * 60_000;
const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

function lockHolderAlive(lock: string): boolean {
  try {
    const pid = Number(readFileSync(path.join(lock, "pid"), "utf8"));
    process.kill(pid, 0);
    return Date.now() - statSync(lock).mtimeMs < LOCK_STALE_MS;
  } catch {
    // No pid yet (just taken) counts as alive for a moment.
    try {
      return Date.now() - statSync(lock).mtimeMs < 5_000;
    } catch {
      return false;
    }
  }
}

/**
 * The cached value for `key`, or `generate()`'s, written to the cache. `key` names the value and its non-code inputs
 * (e.g. `option-reference-forever-v1.15.0`); `entry` is the generator's entry module, whose code is hashed into the key.
 */
export async function generatedCache<T>(key: string, entry: string, generate: () => Promise<T>): Promise<Generated<T>> {
  const file = generatedFile(key, entry);
  const lock = `${file}.lock`;
  await mkdir(GENERATED_CACHE_DIR, { recursive: true });
  for (;;) {
    const cached = await readGenerated<T>(key, entry);
    if (cached !== undefined) return { value: cached, fresh: false, file };
    try {
      await mkdir(lock);
    } catch {
      if (!lockHolderAlive(lock)) await rm(lock, { recursive: true, force: true });
      else await sleep(500);
      continue;
    }
    try {
      await writeFile(path.join(lock, "pid"), String(process.pid));
      const value = await generate();
      await writeGenerated(key, entry, value);
      return { value, fresh: true, file };
    } finally {
      await rm(lock, { recursive: true, force: true });
    }
  }
}

/** The cache file of `key` for the current code of `entry`. */
export const generatedFile = (key: string, entry: string) => path.join(GENERATED_CACHE_DIR, `${key}-${sourceHash(entry)}.json`);

/** The cached value of `key` for the current code of `entry`, if there is one. */
export async function readGenerated<T>(key: string, entry: string): Promise<T | undefined> {
  try {
    return JSON.parse(await readFile(generatedFile(key, entry), "utf8")) as T;
  } catch {
    return undefined;
  }
}

/** Caches `value` as `key`'s for the current code of `entry` (it must have been generated by that code). */
export async function writeGenerated(key: string, entry: string, value: unknown): Promise<void> {
  const file = generatedFile(key, entry);
  await mkdir(GENERATED_CACHE_DIR, { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  await writeFile(tmp, JSON.stringify(value));
  await rename(tmp, file);
}
